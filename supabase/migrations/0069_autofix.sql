-- =============================================================
-- 0069_autofix.sql
-- The auto-fixer (Nic, 2026-11-04): Claude sorts and fixes the Bug and
-- Crashes tabs overnight; Nic approves each fix on the bug bot.
-- Spec: docs/superpowers/specs/2026-11-04-auto-fixer-design.md
--
-- · crash_logs / bug_reports gain build_id — which copy of the app the person
--   was running (the same 12-char hash /api/version reports). Lets the fixer
--   tell "an old tab after a deploy" from a live fault.
-- · crash_logs.autofix_item_id — every crash row is traceable to the one
--   problem it belongs to, so 24 copies of one crash are fixed once.
-- · bug_reports.status gains 'closed' — junk, wishes and noise are closed with
--   a reason rather than left open forever.
-- · autofix_items / autofix_runs / autofix_chat — the fixer's state, its runs
--   (for the watchdog and daily cap) and the bug-bot conversation.
--
-- Additive only: nothing existing is dropped or rewritten. Every read of these
-- objects in the app is fail-soft, so code can deploy ahead of this file.
-- All writes go through server routes on the service key; RLS allows admin
-- reads only.
-- =============================================================

create table public.autofix_items (
  id               uuid        primary key default gen_random_uuid(),
  -- The short number Nic sees on Telegram ("fix 12"). Global, so a number
  -- never means two things on different days.
  no               int         generated by default as identity unique,
  source           text        not null check (source in ('bug', 'crash')),
  bug_report_id    uuid        unique references public.bug_reports(id) on delete set null,
  crash_signature  text,
  verdict          text        check (verdict in ('fix', 'wish', 'junk', 'noise', 'already_fixed', 'known', 'unclear', 'needs_session')),
  severity         text        check (severity in ('major', 'minor')),
  title            text,
  summary          text,
  reason           text,
  whats_new_line   text,
  status           text        not null default 'new'
                   check (status in ('new', 'fixing', 'awaiting_nic', 'going_live', 'live', 'retry', 'dropped', 'closed', 'needs_session')),
  branch           text,
  head_sha         text,
  preview_url      text,
  diff_files       int,
  diff_lines       int,
  merge_sha        text,
  going_live_at    timestamptz,
  live_at          timestamptz,
  live_build_id    text,
  dev_sync_needed  boolean     not null default false,
  attempts         int         not null default 0,
  nic_notes        jsonb       not null default '[]'::jsonb,
  reported_run_id  uuid,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index autofix_items_signature_idx on public.autofix_items (crash_signature);
create index autofix_items_status_idx    on public.autofix_items (status);

create table public.autofix_runs (
  id           uuid        primary key default gen_random_uuid(),
  kind         text        not null check (kind in ('nightly', 'retry')),
  fired_at     timestamptz not null default now(),
  session_url  text,
  finished_at  timestamptz,
  outcome      text,
  alerted      boolean     not null default false
);

create index autofix_runs_fired_idx on public.autofix_runs (fired_at desc);

create table public.autofix_chat (
  id                  uuid        primary key default gen_random_uuid(),
  role                text        not null check (role in ('nic', 'bot')),
  text                text        not null,
  -- Telegram retries a webhook it thinks failed; unique = each message once.
  telegram_update_id  bigint      unique,
  created_at          timestamptz not null default now()
);

create index autofix_chat_created_idx on public.autofix_chat (created_at desc);

alter table public.crash_logs
  add column if not exists build_id        text,
  add column if not exists autofix_item_id uuid references public.autofix_items(id) on delete set null;

create index if not exists crash_logs_autofix_item_idx on public.crash_logs (autofix_item_id);

alter table public.bug_reports
  add column if not exists build_id text;

alter table public.bug_reports drop constraint if exists bug_reports_status_check;
alter table public.bug_reports
  add constraint bug_reports_status_check check (status in ('open', 'fixed', 'closed'));

-- ── RLS: admin may read; nothing else through the API ─────────────────────
alter table public.autofix_items enable row level security;
alter table public.autofix_runs  enable row level security;
alter table public.autofix_chat  enable row level security;

create policy "autofix_items: admin select" on public.autofix_items
  for select using (get_my_role() = 'admin');
create policy "autofix_runs: admin select" on public.autofix_runs
  for select using (get_my_role() = 'admin');
create policy "autofix_chat: admin select" on public.autofix_chat
  for select using (get_my_role() = 'admin');

-- Data API grants (CLAUDE.md hard rule, Supabase change of 2026-10-30). Never anon.
grant select, insert, update, delete on public.autofix_items to authenticated;
grant select, insert, update, delete on public.autofix_items to service_role;
grant select, insert, update, delete on public.autofix_runs  to authenticated;
grant select, insert, update, delete on public.autofix_runs  to service_role;
grant select, insert, update, delete on public.autofix_chat  to authenticated;
grant select, insert, update, delete on public.autofix_chat  to service_role;
-- autofix_items.no is an identity column — its sequence needs the same two roles.
grant usage, select on sequence public.autofix_items_no_seq to authenticated;
grant usage, select on sequence public.autofix_items_no_seq to service_role;
